-- Testing and Feedback Kit: the database, for Supabase.
-- https://github.com/mani-kanasani/testing-feedback-kit
--
-- What it adds, every name starting with feedback, so nothing of yours is touched:
--   feedback_members    who is on the list, and their role: approver, member or agent
--   feedback_tickets    the tickets
--   feedback_comments   what was said on them
--   feedback_files      their screenshots and recordings, kept in the private bucket feedback-files
--   feedback_events     who did what, in words, written only by the database
--   feedback_notices    the bell: one line a ticket and a person
-- People on the list read. Every write goes through a function below, which checks who is asking. Nothing is deleted.
--
-- The rules it keeps, whatever screen or agent is calling:
--   1. Only people on feedback_members see or touch anything.
--   2. Only whoever filed a ticket, or an approver, changes what it says. Anyone on the list moves it and comments.
--   3. An agent never marks a ticket Done or Won't do. A person does, after testing it again.
--   4. A ticket is marked Done only from In review, and not by whoever moved it there. Someone else tests it.
--   5. Every change is written down in feedback_events.
--
-- Two functions are where your app meets the kit. feedback_email() says who is asking, and feedback_role() says what
-- they may do. If your app signs people in another way, or keeps roles in its own table, change those two and nothing
-- else (INSTALL.md, "Your own roles").
--
-- The way back: supabase/undo.sql.

-- ---------- tables

create table public.feedback_members (
  email text primary key check (email = lower(btrim(email)) and email like '%_@_%'),
  name text not null default '' check (char_length(name) <= 80),
  role text not null default 'member' check (role in ('approver', 'member', 'agent')),
  added_by text,
  added_at timestamptz not null default now()
);

create table public.feedback_tickets (
  id uuid primary key default gen_random_uuid(),
  number integer generated by default as identity unique,
  title text not null check (char_length(btrim(title)) between 1 and 200),
  body text not null default '' check (char_length(body) <= 10000),
  area text not null default 'Something else' check (char_length(btrim(area)) between 1 and 60),
  kind text not null default 'bug' check (kind in ('bug', 'change', 'feature')),
  severity text not null default 'medium' check (severity in ('low', 'medium', 'high', 'critical')),
  status text not null default 'new' check (status in ('new', 'in_progress', 'in_review', 'done', 'wont_do')),
  -- A path in the app and nothing else: no address of another site, no query string, no line breaks. An agent reads it.
  page text check (char_length(page) <= 300 and page ~ '^/([^/[:space:]?#][^[:space:]?#]*)?$'),
  device text check (char_length(device) <= 120 and device !~ '[[:cntrl:]]'),
  filed_by text not null,
  filed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  status_by text,
  status_at timestamptz,
  review_by text
);
create index feedback_tickets_status_filed on public.feedback_tickets (status, filed_at desc);

create table public.feedback_comments (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.feedback_tickets (id) on delete cascade,
  author text not null,
  body text not null check (char_length(btrim(body)) between 1 and 5000),
  at timestamptz not null default now()
);
create index feedback_comments_ticket on public.feedback_comments (ticket_id, at);

create table public.feedback_files (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.feedback_tickets (id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 200),
  path text not null unique,
  size_bytes bigint not null default 0,
  mime text not null default '',
  added_by text not null,
  added_at timestamptz not null default now()
);
create index feedback_files_ticket on public.feedback_files (ticket_id, added_at);

create table public.feedback_events (
  id bigint generated always as identity primary key,
  ticket_id uuid not null references public.feedback_tickets (id) on delete cascade,
  actor text not null,
  what text not null,
  at timestamptz not null default now()
);
create index feedback_events_ticket on public.feedback_events (ticket_id, at);

-- Something new about the same ticket replaces a person's line and makes it unread again.
create table public.feedback_notices (
  ticket_id uuid not null references public.feedback_tickets (id) on delete cascade,
  member text not null,
  reason text not null check (reason in ('filed', 'moved', 'comment')),
  actor text not null,
  to_status text,
  note text,
  at timestamptz not null default now(),
  read_at timestamptz,
  primary key (ticket_id, member)
);
create index feedback_notices_member on public.feedback_notices (member, at desc);

-- ---------- who is asking. The two functions to change if your app works another way.

-- The signed-in person's address, in lower case, once they have confirmed it. Null for anyone else.
create function public.feedback_email() returns text
language sql stable security definer
set search_path = ''
as $$
  select lower(u.email) from auth.users u where u.id = auth.uid() and u.email_confirmed_at is not null
$$;

-- Their role on the list: approver, member or agent. Null when they are not on it.
create function public.feedback_role() returns text
language sql stable security definer
set search_path = ''
as $$
  select m.role from public.feedback_members m where m.email = public.feedback_email()
$$;

-- What the screens ask first: who am I here.
create function public.feedback_whoami() returns jsonb
language sql stable security definer
set search_path = ''
as $$
  select jsonb_build_object('email', m.email, 'name', m.name, 'role', m.role)
  from public.feedback_members m where m.email = public.feedback_email()
$$;

