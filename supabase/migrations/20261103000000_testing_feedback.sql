-- ---------- words the history uses

create function public.feedback_status_word(p_status text) returns text
language sql immutable
set search_path = ''
as $$
  select case p_status
    when 'new' then 'New'
    when 'in_progress' then 'In progress'
    when 'in_review' then 'In review'
    when 'done' then 'Done'
    when 'wont_do' then 'Won''t do'
    else p_status
  end
$$;

create function public.feedback_kind_word(p_kind text) returns text
language sql immutable
set search_path = ''
as $$
  select case p_kind when 'bug' then 'bug' when 'change' then 'change' when 'feature' then 'new feature' else p_kind end
$$;

-- ---------- filing a ticket: anyone on the list

create function public.feedback_file(p jsonb) returns public.feedback_tickets
language plpgsql security definer
set search_path = ''
as $$
declare
  me text := public.feedback_email();
  v_title text := btrim(coalesce(p ->> 'title', ''));
  v_body text := btrim(coalesce(p ->> 'body', ''));
  v_area text := btrim(coalesce(nullif(btrim(p ->> 'area'), ''), 'Something else'));
  v_kind text := coalesce(nullif(p ->> 'kind', ''), 'bug');
  v_severity text := coalesce(nullif(p ->> 'severity', ''), 'medium');
  v_page text := left(btrim(coalesce(p ->> 'page', '')), 300);
  v_device text := nullif(left(btrim(regexp_replace(coalesce(p ->> 'device', ''), '[[:cntrl:]]+', ' ', 'g')), 120), '');
  f public.feedback_tickets;
begin
  if public.feedback_role() is null then
    raise exception 'You are not on the feedback list for this app.';
  end if;
  if v_title = '' then
    raise exception 'The ticket needs a title.';
  end if;
  if char_length(v_title) > 200 then
    raise exception 'A title is 200 characters at most.';
  end if;
  if char_length(v_body) > 10000 then
    raise exception 'What happened is 10,000 characters at most.';
  end if;
  if char_length(v_area) > 60 then
    raise exception 'The part of the app is 60 characters at most.';
  end if;
  if v_kind not in ('bug', 'change', 'feature') then
    raise exception 'A ticket is a bug, a change or a new feature.';
  end if;
  if v_severity not in ('low', 'medium', 'high', 'critical') then
    raise exception 'Severity is low, medium, high or critical.';
  end if;
  -- A query string or a part after # is cut off, and anything that is not a plain path in the app is dropped.
  v_page := btrim(split_part(split_part(v_page, '?', 1), '#', 1));
  if v_page !~ '^/([^/[:space:]?#][^[:space:]?#]*)?$' then
    v_page := null;
  end if;

  insert into public.feedback_tickets (title, body, area, kind, severity, page, device, filed_by)
  values (v_title, v_body, v_area, v_kind, v_severity, v_page, v_device, me)
  returning * into f;
  insert into public.feedback_events (ticket_id, actor, what) values (f.id, me, 'filed it');

  -- Every approver's bell, never the bell of whoever filed it.
  insert into public.feedback_notices (ticket_id, member, reason, actor, at)
  select f.id, m.email, 'filed', me, now() from public.feedback_members m where m.role = 'approver' and m.email <> me
  on conflict (ticket_id, member) do update
    set reason = excluded.reason, actor = excluded.actor, to_status = null, note = null, at = excluded.at, read_at = null;
  return f;
end $$;

-- ---------- changing what a ticket says: whoever filed it, or an approver

create function public.feedback_edit(p_id uuid, p jsonb) returns public.feedback_tickets
language plpgsql security definer
set search_path = ''
as $$
declare
  me text := public.feedback_email();
  v_role text := public.feedback_role();
  f public.feedback_tickets;
  v_title text;
  v_body text;
  v_area text;
  v_kind text;
  v_severity text;
  v_changed text[] := '{}';
begin
  if v_role is null then
    raise exception 'You are not on the feedback list for this app.';
  end if;
  select * into f from public.feedback_tickets where id = p_id;
  if f.id is null then
    raise exception 'That ticket is not there.';
  end if;
  if f.filed_by is distinct from me and v_role is distinct from 'approver' then
    raise exception 'Only whoever filed a ticket, or an approver, changes what it says. Leave a comment instead.';
  end if;
  v_title := case when p ? 'title' then btrim(coalesce(p ->> 'title', '')) else f.title end;
  v_body := case when p ? 'body' then btrim(coalesce(p ->> 'body', '')) else f.body end;
  v_area := case when p ? 'area' then btrim(coalesce(nullif(btrim(p ->> 'area'), ''), 'Something else')) else f.area end;
  v_kind := case when p ? 'kind' then coalesce(p ->> 'kind', '') else f.kind end;
  v_severity := case when p ? 'severity' then coalesce(p ->> 'severity', '') else f.severity end;
  if v_title = '' then
    raise exception 'The ticket needs a title.';
  end if;
  if char_length(v_title) > 200 then
    raise exception 'A title is 200 characters at most.';
  end if;
  if char_length(v_body) > 10000 then
    raise exception 'What happened is 10,000 characters at most.';
  end if;
  if char_length(v_area) > 60 then
    raise exception 'The part of the app is 60 characters at most.';
  end if;
  if v_kind not in ('bug', 'change', 'feature') then
    raise exception 'A ticket is a bug, a change or a new feature.';
  end if;
  if v_severity not in ('low', 'medium', 'high', 'critical') then
    raise exception 'Severity is low, medium, high or critical.';
  end if;

  if v_title is distinct from f.title then v_changed := v_changed || 'the title'::text; end if;
  if v_body is distinct from f.body then v_changed := v_changed || 'what happened'::text; end if;
  if v_area is distinct from f.area then v_changed := v_changed || ('the part of the app to ' || v_area); end if;
  if v_kind is distinct from f.kind then v_changed := v_changed || ('the kind to ' || public.feedback_kind_word(v_kind)); end if;
  if v_severity is distinct from f.severity then v_changed := v_changed || ('the severity from ' || f.severity || ' to ' || v_severity); end if;
  if cardinality(v_changed) = 0 then
    return f;
  end if;

  update public.feedback_tickets
  set title = v_title, body = v_body, area = v_area, kind = v_kind, severity = v_severity, updated_at = now()
  where id = p_id
  returning * into f;
  insert into public.feedback_events (ticket_id, actor, what) values (f.id, me, 'changed ' || array_to_string(v_changed, ', '));
  return f;
end $$;

-- ---------- moving a ticket: anyone on the list, within rules 3 and 4. Won't do may come from any status.

create function public.feedback_move(p_id uuid, p_status text, p_note text default null) returns public.feedback_tickets
language plpgsql security definer
set search_path = ''
as $$
declare
  me text := public.feedback_email();
  v_role text := public.feedback_role();
  f public.feedback_tickets;
  v_from text;
  v_note text := btrim(coalesce(p_note, ''));
begin
  if v_role is null then
    raise exception 'You are not on the feedback list for this app.';
  end if;
  select * into f from public.feedback_tickets where id = p_id;
  if f.id is null then
    raise exception 'That ticket is not there.';
  end if;
  if p_status is null or p_status not in ('new', 'in_progress', 'in_review', 'done', 'wont_do') then
    raise exception 'A ticket is New, In progress, In review, Done or Won''t do.';
  end if;
  if v_role = 'agent' and p_status in ('done', 'wont_do') then
    raise exception 'Only a person marks a ticket Done or Won''t do, after testing it again. Move it to In review.';
  end if;
  if p_status = 'done' and f.status <> 'done' and f.status <> 'in_review' then
    raise exception 'A ticket is tested in In review before it is Done. Move it to In review first.';
  end if;
  if p_status = 'done' and f.status = 'in_review' and f.review_by = me then
    raise exception 'You moved this ticket to In review, so someone else tests it and marks it Done.';
  end if;
  if char_length(v_note) > 5000 then
    raise exception 'A comment is 5,000 characters at most.';
  end if;
  if f.status = p_status and v_note = '' then
    return f;
  end if;

  v_from := f.status;
  if f.status <> p_status then
    update public.feedback_tickets
    set status = p_status, status_by = me, status_at = now(), updated_at = now(),
        review_by = case when p_status = 'in_review' then me else review_by end
    where id = p_id
    returning * into f;
    insert into public.feedback_events (ticket_id, actor, what)
    values (f.id, me, 'moved it from ' || public.feedback_status_word(v_from) || ' to ' || public.feedback_status_word(p_status));
  end if;
  if v_note <> '' then
    insert into public.feedback_comments (ticket_id, author, body) values (f.id, me, v_note);
  end if;

  -- Whoever filed it is told, unless they did it themselves.
  if f.filed_by is distinct from me then
    insert into public.feedback_notices (ticket_id, member, reason, actor, to_status, note, at)
    values (f.id, f.filed_by, case when v_from <> p_status then 'moved' else 'comment' end, me,
            case when v_from <> p_status then p_status end, nullif(left(v_note, 300), ''), now())
    on conflict (ticket_id, member) do update
      set reason = excluded.reason, actor = excluded.actor, to_status = excluded.to_status, note = excluded.note, at = excluded.at, read_at = null;
  end if;
  return f;
end $$;

-- ---------- comments: anyone on the list

create function public.feedback_comment(p_id uuid, p_body text) returns public.feedback_comments
language plpgsql security definer
set search_path = ''
as $$
declare
  me text := public.feedback_email();
  f public.feedback_tickets;
  v_body text := btrim(coalesce(p_body, ''));
  c public.feedback_comments;
begin
  if public.feedback_role() is null then
    raise exception 'You are not on the feedback list for this app.';
  end if;
  select * into f from public.feedback_tickets where id = p_id;
  if f.id is null then
    raise exception 'That ticket is not there.';
  end if;
  if v_body = '' then
    raise exception 'The comment is empty.';
  end if;
  if char_length(v_body) > 5000 then
    raise exception 'A comment is 5,000 characters at most.';
  end if;
  insert into public.feedback_comments (ticket_id, author, body) values (f.id, me, v_body) returning * into c;
  update public.feedback_tickets set updated_at = now() where id = f.id;
  if f.filed_by is distinct from me then
    insert into public.feedback_notices (ticket_id, member, reason, actor, to_status, note, at)
    values (f.id, f.filed_by, 'comment', me, null, left(v_body, 300), now())
    on conflict (ticket_id, member) do update
      set reason = excluded.reason, actor = excluded.actor, to_status = null, note = excluded.note, at = excluded.at, read_at = null;
  end if;
  return c;
end $$;

-- ---------- files: into the ticket's own folder of the bucket, <ticket id>/<random>-<name>

-- The ticket a stored file belongs to, from its path. Null when the path is not a ticket's folder.
create function public.feedback_folder_ticket(p_path text) returns uuid
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_part text := split_part(coalesce(p_path, ''), '/', 1);
begin
  if v_part !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' or split_part(p_path, '/', 2) = '' then
    return null;
  end if;
  return (select t.id from public.feedback_tickets t where t.id = v_part::uuid);
end $$;

-- Adds a file the caller has just uploaded to the ticket's folder. Its size and type are read from storage, never taken
-- from the caller, and a file someone else uploaded cannot be added by you.
create function public.feedback_add_file(p_id uuid, p_name text, p_path text) returns public.feedback_files
language plpgsql security definer
set search_path = ''
as $$
declare
  me text := public.feedback_email();
  v_name text := btrim(regexp_replace(coalesce(p_name, ''), '[[:cntrl:]]+', ' ', 'g'));
  o record;
  r public.feedback_files;
begin
  if public.feedback_role() is null then
    raise exception 'You are not on the feedback list for this app.';
  end if;
  if not exists (select 1 from public.feedback_tickets where id = p_id) then
    raise exception 'That ticket is not there.';
  end if;
  if v_name = '' then
    raise exception 'The file needs a name.';
  end if;
  select x.metadata, x.owner_id into o from storage.objects x where x.bucket_id = 'feedback-files' and x.name = p_path;
  if public.feedback_folder_ticket(p_path) is distinct from p_id or o is null or o.owner_id is distinct from auth.uid()::text then
    raise exception 'That file was not stored for this ticket.';
  end if;
  insert into public.feedback_files (ticket_id, name, path, size_bytes, mime, added_by)
  values (p_id, left(v_name, 200), p_path, greatest(coalesce((o.metadata ->> 'size')::bigint, 0), 0), left(coalesce(o.metadata ->> 'mimetype', ''), 120), me)
  returning * into r;
  insert into public.feedback_events (ticket_id, actor, what) values (p_id, me, 'added a file, ' || left(v_name, 200));
  update public.feedback_tickets set updated_at = now() where id = p_id;
  return r;
end $$;

-- ---------- the bell: your own lines only

create function public.feedback_my_notices() returns jsonb
language sql stable security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(row_to_json(x) order by x.at desc), '[]'::jsonb)
  from (
    select n.ticket_id, t.number, t.title, n.reason, n.actor, n.to_status, n.note, n.at, n.read_at is not null as read
    from public.feedback_notices n
    join public.feedback_tickets t on t.id = n.ticket_id
    where n.member = public.feedback_email()
    order by n.at desc
    limit 50
  ) x
$$;

create function public.feedback_mark_read(p_id uuid) returns void
language sql security definer
set search_path = ''
as $$
  update public.feedback_notices set read_at = now()
  where ticket_id = p_id and member = public.feedback_email() and read_at is null
$$;

create function public.feedback_mark_all_read() returns void
language sql security definer
set search_path = ''
as $$
  update public.feedback_notices set read_at = now()
  where member = public.feedback_email() and read_at is null
$$;

-- ---------- the list itself: approvers add and remove people. The first approver is added by hand (INSTALL.md).

create function public.feedback_add_member(p_email text, p_name text, p_role text) returns public.feedback_members
language plpgsql security definer
set search_path = ''
as $$
declare
  me text := public.feedback_email();
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_name text := btrim(coalesce(p_name, ''));
  v_role text := coalesce(nullif(p_role, ''), 'member');
  r public.feedback_members;
begin
  if public.feedback_role() is distinct from 'approver' then
    raise exception 'Only an approver changes the feedback list.';
  end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'That is not an email address.';
  end if;
  if v_role not in ('approver', 'member', 'agent') then
    raise exception 'A role is approver, member or agent.';
  end if;
  if v_role <> 'approver'
     and exists (select 1 from public.feedback_members where email = v_email and role = 'approver')
     and (select count(*) from public.feedback_members where role = 'approver') = 1 then
    raise exception 'The list needs at least one approver.';
  end if;
  insert into public.feedback_members (email, name, role, added_by)
  values (v_email, coalesce(nullif(left(v_name, 80), ''), split_part(v_email, '@', 1)), v_role, me)
  on conflict (email) do update set name = coalesce(nullif(left(v_name, 80), ''), public.feedback_members.name), role = excluded.role
  returning * into r;
  return r;
end $$;

create function public.feedback_remove_member(p_email text) returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
begin
  if public.feedback_role() is distinct from 'approver' then
    raise exception 'Only an approver changes the feedback list.';
  end if;
  if exists (select 1 from public.feedback_members where email = v_email and role = 'approver')
     and (select count(*) from public.feedback_members where role = 'approver') = 1 then
    raise exception 'The list needs at least one approver.';
  end if;
  -- Their tickets, comments and history stay, under their address.
  delete from public.feedback_members where email = v_email;
end $$;

-- ---------- the bucket: the list reads, and adds files to a ticket's own folder. Nothing is replaced or deleted.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('feedback-files', 'feedback-files', false, 52428800,
        array['image/png', 'image/jpeg', 'image/gif', 'image/webp', 'application/pdf', 'video/mp4', 'video/quicktime', 'video/webm'])
on conflict (id) do nothing;

create policy "feedback-files: the list reads" on storage.objects for select to authenticated
  using (bucket_id = 'feedback-files' and (select public.feedback_role()) is not null);

create policy "feedback-files: the list adds to a ticket's folder" on storage.objects for insert to authenticated
  with check (bucket_id = 'feedback-files' and (select public.feedback_role()) is not null and public.feedback_folder_ticket(name) is not null);

